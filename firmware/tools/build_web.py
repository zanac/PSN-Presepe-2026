#!/usr/bin/env python3
"""Build the web pages served by the ESP8266 into firmware/PSN-Presepe-WiFi/pagine_web.h.

Usage: python3 firmware/tools/build_web.py [--check]

Pages (gzip-compressed, stored in flash with PROGMEM):
  /        firmware/web/pannello.html                  control panel and web test
  /config  simulation_web/simulator.template.html      editor of PRESEPE.INI with live
           preview; the same page as the browser simulator, with window.PRESEPE_DEVICE = true
           so that it loads and saves the file through the board.

It also writes the demo in demo/ (index.html = panel, config.html = editor): the same two
pages with firmware/web/demo_mock.js, a simulated board that answers /api/* in the browser
(it uses the repo's PRESEPE.INI and the simulator's parser and light engine), so anyone
browsing the repository can try them without hardware.

Run it after every change to those files (or to PRESEPE.INI) and commit what it regenerates.
--check only compares: exit status 1 if pagine_web.h or demo/ is out of date (used by CI).
"""
import gzip, io, json, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parents[2]
OUT = root / "firmware/PSN-Presepe-WiFi/pagine_web.h"

HEAD = ('<!doctype html>\n<html lang="it">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
        '<style>html,body{margin:0}[hidden]{display:none!important}</style>\n'
        '</head>\n<body>\n')
TAIL = '\n</body>\n</html>\n'


def page(body: str) -> bytes:
    return (HEAD + body + TAIL).encode("utf-8")


def gz(data: bytes) -> bytes:
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0) as f:
        f.write(data)
    return buf.getvalue()


def c_array(name: str, data: bytes) -> str:
    lines = [f"const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"const size_t {name}_LEN = {len(data)};")
    return "\n".join(lines)


tpl = (root / "simulation_web/simulator.template.html").read_text(encoding="utf-8")
if tpl.count("__INI__") != 1 or tpl.count("<script>") != 1:
    raise SystemExit("simulator.template.html: expected one __INI__ and one <script>")
config = tpl.replace("__INI__", '""').replace("<script>", "<script>window.PRESEPE_DEVICE = true;</script>\n<script>", 1)
pannello = (root / "firmware/web/pannello.html").read_text(encoding="utf-8")

pages = {"PAGINA_CONFIG": gz(page(config)), "PAGINA_PANNELLO": gz(page(pannello))}

# ------------------------------------------------------------------ demo/
script = tpl[tpl.index("<script>") + len("<script>"):tpl.index("</script>")]
a = script.index("const FASI = ")
b = script.index("// ---------------------------------------------------------------- interfaccia")
engine = ("function DEMO_ENGINE() {\n" + script[a:b] +
          "return { parse, faseDi, inizio, fine, colore, rele, STRISCE };\n}\n")
ini = (root / "firmware/PSN-Presepe/PRESEPE.INI").read_text(encoding="utf-8")
mock = (root / "firmware/web/demo_mock.js").read_text(encoding="utf-8")
DEMO_CSS = ("<style>.demo-banner{margin:-16px -16px 14px;"
            "padding:8px 16px;background:var(--accent);color:var(--accent-ink);font:500 13px/1.4 system-ui,sans-serif}"
            ".demo-banner a{color:inherit;font-weight:700}</style>\n")
demo_js = ("<script>\n// DEMO: simulated board, see firmware/web/demo_mock.js\nconst DEMO_INI = " + json.dumps(ini) + ";\n"
           + engine + mock + "</script>\n")


def demo(html: str, title: str) -> str:
    html = html.replace('href="/config"', 'href="config.html"').replace('href="/"', 'href="index.html"')
    i = html.index("<script")
    head = HEAD.replace("</head>", DEMO_CSS + "</head>")
    out = head + html[:i] + demo_js + html[i:] + TAIL
    out = re.sub(r"<title>[^<]*</title>", "<title>" + title + "</title>", out, count=1)
    return out.replace("<head>", "<head>\n<!-- GENERATED by firmware/tools/build_web.py - do not edit by hand -->", 1)


demos = {
    root / "demo/index.html": demo(pannello, "Pannello presepe (demo)"),
    root / "demo/config.html": demo(config, "Configurazione presepe (demo)"),
}
text = ("// GENERATED by firmware/tools/build_web.py - do not edit by hand.\n"
        "// Sources: simulation_web/simulator.template.html (/config), firmware/web/pannello.html (/).\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        + "\n\n".join(c_array(n, d) for n, d in pages.items()) + "\n")

outputs = {OUT: text, **demos}
if "--check" in sys.argv:
    stale = [str(f.relative_to(root)) for f, s in outputs.items() if not f.exists() or f.read_text(encoding="utf-8") != s]
    if stale:
        raise SystemExit(", ".join(stale) + " out of date: run python3 firmware/tools/build_web.py")
    print("pagine_web.h and demo/ up to date")
else:
    for f, s in outputs.items():
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(s, encoding="utf-8")
    print(f"wrote {OUT.relative_to(root)}: " + ", ".join(f"{n} {len(d)} bytes gz" for n, d in pages.items()))
    print("wrote " + ", ".join(f"{f.relative_to(root)} ({len(s.encode())} bytes)" for f, s in demos.items()))
